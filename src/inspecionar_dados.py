from pathlib import Path
import pandas as pd

DATA_DIR = Path(__file__).resolve().parent.parent / "data"

arquivos = [
    "desafio_tecnico_ai_eng - categories.csv",
    "desafio_tecnico_ai_eng - customers.csv",
    "desafio_tecnico_ai_eng - order_items.csv",
    "desafio_tecnico_ai_eng - orders.csv",
    "desafio_tecnico_ai_eng - products.csv",
    "desafio_tecnico_ai_eng - promotions.csv",
]

for arquivo in arquivos:
    caminho = DATA_DIR / arquivo

    df = pd.read_csv(caminho)

    print(f"\n{'=' * 50}")
    print(f"ARQUIVO: {arquivo}")
    print(f"LINHAS: {df.shape[0]}")
    print(f"COLUNAS: {df.shape[1]}")
    print(f"NOMES DAS COLUNAS: {df.columns.tolist()}")
    print(f"TIPOS DE DADOS:\n{df.dtypes}")
    print(f"VALORES NULOS: {df.isna().sum().sum()}")

    if arquivo == "products.csv":
        print(f"EXEMPLO:\n{df.head(3)}")